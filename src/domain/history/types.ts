import type { FailureClass, Outcome, OperationContext, WriteKind } from '../operations';
import type { DepthId, PrivilegeId } from '../privileges';

// The operation ledger (issue #274). Pure data, host-free. Ids, timestamps, plain-language descriptions and classified outcomes only:
// never tokens, never record contents. Mirrors Core/History of the XrmToolBox tool, in the vocabulary of the PPTB write contract.

/** A step that has been planned and has no recorded result yet. */
export type StepOutcome = Outcome | 'pending';

/** What the whole operation is. `inProgress` only while the operation has not ended; `succeeded` only when every step is verified. */
export type OperationStatus = Outcome | 'inProgress';

// ---- minimal verified state around a step (schema v2) ----------------------------------------------------------------------------------
// Only ids, depths and booleans: enough to compare "what is there now" with "what was recorded" and to compute a compensating write. No
// names of people, no record contents. `before` exists only when it was READ before the write; `after` only from the verifying re-read.

/** The depth one role record holds for one privilege of one table ('None' = not held). */
export interface PrivilegeDepthState {
  readonly kind: 'privilegeDepth';
  readonly table: string;
  readonly roleId: string;
  readonly privilegeId: string;
  readonly privilege: PrivilegeId;
  readonly depth: DepthId;
}

/** Whether a user directly holds a role. */
export interface RoleHeldState {
  readonly kind: 'roleHeld';
  readonly userId: string;
  readonly roleId: string;
  readonly held: boolean;
}

/** Where a user is and which roles they directly hold (`roleIds` null = the role list was not read completely). */
export interface UserPlacementState {
  readonly kind: 'userPlacement';
  readonly userId: string;
  readonly businessUnitId: string;
  readonly roleIds: readonly string[] | null;
}

export type TargetState = PrivilegeDepthState | RoleHeldState | UserPlacementState;

export interface StepRecord {
  /** Position in the confirmed plan (0-based). Steps are sent in this order. */
  readonly index: number;
  readonly key: string;
  readonly kind: WriteKind;
  /** The intended change in plain language, as shown at confirmation. */
  readonly description: string;
  readonly outcome: StepOutcome;
  /** True only when a re-read confirmed the end state. Always false unless `outcome` is `succeeded`. */
  readonly verified: boolean;
  readonly failure: FailureClass;
  readonly message: string;
  /** Troubleshooting only (failure kind, Dataverse error code). */
  readonly technical?: string;
  /** Request/correlation id the service returned for this step, when the caller had one. */
  readonly serverCorrelationId?: string;
  readonly startedAtMs?: number;
  readonly endedAtMs?: number;
  /** State read right before the write (schema v2). Absent when it was not read: the step is then not restorable. */
  readonly before?: TargetState;
  /** State found by the verifying re-read after the write (schema v2). */
  readonly after?: TargetState;
  /** Checksum of the step key and its states; a stored record whose states no longer match it is not restorable. */
  readonly stateChecksum?: string;
  /** `failed` when the stored states did not match their checksum (they were dropped, the step is not restorable). */
  readonly stateIntegrity?: 'ok' | 'failed';
}

export interface OperationRecord {
  /** 1 = legacy (no before-state, never automatically restorable), 2 = records minimal before/after states. */
  readonly schemaVersion: 1 | 2;
  readonly operationId: string;
  /** Random id generated by this tool for the operation; groups every log line and export row. */
  readonly correlationId: string;
  /** Request/correlation id of the service, when the caller has one. */
  readonly serverCorrelationId?: string;
  readonly environmentId: string;
  /** Who confirmed the plan. */
  readonly actor: string;
  readonly planHash: string;
  readonly source: OperationContext['source'];
  readonly sourceOperationId?: string;
  /** For a restore: the operations it reverses. */
  readonly sourceOperationIds?: readonly string[];
  readonly startedAtMs: number;
  readonly endedAtMs?: number;
  readonly steps: readonly StepRecord[];
}
